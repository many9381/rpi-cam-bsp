#!/usr/bin/env python3
"""Convert the firmware's npm lock to authenticated, ordinary BitBake fetches.

Print to stdout; --check compares an existing include without changing files.
The BitBake npm/npmsw fetchers are disabled in the pinned release. Keeping this
conversion explicit also makes every network input visible in recipe metadata.
"""
from __future__ import annotations

import argparse
import base64
import binascii
import hashlib
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit


def generate(lock_bytes: bytes) -> str:
    document = json.loads(lock_bytes)
    if not isinstance(document, dict) or document.get("lockfileVersion") != 3:
        raise ValueError("expected npm lockfileVersion 3")
    packages = document.get("packages")
    if not isinstance(packages, dict) or not packages:
        raise ValueError("expected a nonempty packages object")
    archives: dict[str, str] = {}
    for location, package in packages.items():
        if location == "":
            continue
        if not isinstance(package, dict):
            raise ValueError("expected a package object")
        if (not location.startswith("node_modules/") or package.get("link")
                or package.get("inBundle")):
            raise ValueError("local or bundled dependencies are not supported")
        url = package.get("resolved", "")
        if not isinstance(url, str):
            raise ValueError("unsupported archive URL")
        parsed = urlsplit(url)
        if (parsed.scheme != "https" or parsed.netloc != "registry.npmjs.org"
                or parsed.query or parsed.fragment
                or not re.fullmatch(r"/[A-Za-z0-9@_./+-]+\.tgz", parsed.path)
                or any(part in (".", "..", "") for part in parsed.path.split("/")[1:])):
            raise ValueError(f"unsupported archive URL: {url!r}")
        integrity = package.get("integrity")
        if not isinstance(integrity, str) or not integrity.startswith("sha512-"):
            raise ValueError("each archive requires SHA-512 integrity")
        try:
            digest = base64.b64decode(integrity[7:], validate=True)
        except (ValueError, binascii.Error) as error:
            raise ValueError("invalid SHA-512 integrity") from error
        if len(digest) != 64:
            raise ValueError("invalid SHA-512 integrity length")
        checksum = digest.hex()
        if url in archives and archives[url] != checksum:
            raise ValueError(f"conflicting integrity for {url}")
        archives[url] = checksum
    if not archives:
        raise ValueError("lock contains no registry archives")

    lines = [
        "# Generated by scripts/firmware_npm_lock.py; do not edit by hand.",
        "# Includes dev/optional dependencies; npm selects native build-host packages.",
        f'CF_NPM_LOCK_SHA256 = "{hashlib.sha256(lock_bytes).hexdigest()}"',
        '',
        'SRC_URI += " \\',
    ]
    entries = []
    for index, (url, checksum) in enumerate(sorted(archives.items())):
        name = f"cf_npm_{index:04d}"
        # Full SHA-256 of the URL avoids flattening collisions between scopes.
        filename = f"camera-firmware-npm-{hashlib.sha256(url.encode()).hexdigest()}.tgz"
        entries.append((name, filename, checksum))
        lines.append(f"    {url};name={name};downloadfilename={filename};unpack=0 \\")
    lines += ['"', '']
    for name, _, checksum in entries:
        lines.append(f'SRC_URI[{name}.sha512sum] = "{checksum}"')
    lines += ['', 'CF_NPM_ARCHIVES = " \\']
    for _, filename, _ in entries:
        lines.append(f"    ${{DL_DIR}}/{filename} \\")
    lines += ['"', '']
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("lock", type=Path, help="firmware web/package-lock.json")
    parser.add_argument("--check", type=Path, metavar="INCLUDE")
    args = parser.parse_args()
    try:
        generated = generate(args.lock.read_bytes())
        if args.check:
            if args.check.read_text(encoding="utf-8") != generated:
                raise ValueError(f"stale npm metadata: regenerate {args.check}")
        else:
            sys.stdout.write(generated)
    except (OSError, ValueError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
