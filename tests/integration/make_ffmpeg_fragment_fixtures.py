#!/usr/bin/env python3
"""Synthetic public-format reproducer: one PSSH and one PCM packet per fragment."""
from pathlib import Path
import argparse
import hashlib
import json
import struct

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('base', type=Path, help='base.mov generated by make_ffmpeg_mov_fixtures.py')
parser.add_argument('output', type=Path)
args = parser.parse_args()
base = args.base
out = args.output
out.mkdir(parents=True, exist_ok=True)
u32 = lambda n: struct.pack('>I',n)
u64 = lambda n: struct.pack('>Q',n)
def box(t,b): return u32(len(b)+8)+t+b
def boxes(b):
    offset=0
    while offset<len(b):
        size=int.from_bytes(b[offset:offset+4],'big')
        assert size>=8 and offset+size<=len(b)
        yield b[offset+4:offset+8],b[offset+8:offset+size]
        offset+=size
    assert offset==len(b)
parts=list(boxes(base.read_bytes()))
prefix=b''.join(box(t,b) for t,b in parts if t in (b'ftyp',b'moov'))
moof=next(b for t,b in parts if t==b'moof')
mdat=next(b for t,b in parts if t==b'mdat')
def fragment(sequence):
    result=b''
    for t,b in boxes(moof):
        if t==b'mfhd': b=b[:4]+u32(sequence+1)
        if t==b'traf':
            children=b''
            for ct,cb in boxes(b):
                if ct==b'tfdt':
                    assert cb[0]==1
                    cb=cb[:4]+u64(sequence*1024)
                children+=box(ct,cb)
            b=children
        result+=box(t,b)
    return box(b'moof',result)+box(b'mdat',mdat)
def record(i):
    sid=bytes([i%251])*16
    payload=bytes([i%239])*(i%11)
    wire=u32(16)+u32(0)+u32(16)+u32(len(payload))+sid+payload
    return box(b'pssh',b'\0\0\0\0'+sid+u32(len(payload))+payload),wire
manifest=[]
for n in (1,7,1024,2048,4096):
    records=[]
    name=f'fragmented-{n}'
    with (out/(name+'.mov')).open('wb') as f:
        f.write(prefix)
        for i in range(n):
            atom,wire=record(i)
            records.append(wire)
            f.write(atom+fragment(i))
    (out/(name+'.0.bin')).write_bytes(u32(n)+b''.join(records))
    manifest.append(dict(name=name,records=n,packets=n,sha256=hashlib.sha256((out/(name+'.mov')).read_bytes()).hexdigest()))
(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest,indent=2))
